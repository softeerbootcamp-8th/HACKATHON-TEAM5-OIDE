package com.example.oide.payment.client;

/**
 * 거래 날짜를 화면 어디에서 읽었는지. 서버가 연도를 어디까지 보정해도 되는지 판단하는 데 쓴다.
 *
 * <p>토스·계좌 내역처럼 날짜가 그룹 헤더에만 있는 화면과, 카드 이용내역처럼 행마다 전체 날짜가
 * 있는 화면을 같은 규칙으로 처리하기 위한 값이다.
 */
public enum DateSource {

	/** 거래 행 자체에 날짜가 있었다. */
	ROW,

	/** 행 위쪽의 날짜 구분 헤더에서 상속했다. */
	HEADER,

	/** 날짜를 찾지 못했다. */
	NONE
}
